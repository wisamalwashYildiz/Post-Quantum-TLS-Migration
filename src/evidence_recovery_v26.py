#!/usr/bin/env python3
"""v2.6 live witness escrow/recovery pilot. Root-trusted receiver model, NOT independent root enclaves.

Uses actual receipts generated by v2.4 live three-hop TLS, then isolates their
recovery in a root-owned temporary escrow. No fabricated recovery verdicts.
"""
import argparse, copy, csv, hashlib, json, os, pwd, secrets, ssl, sys, tempfile, time, uuid
from datetime import datetime, timezone
from pathlib import Path
try:
 import protected_path_v24 as v24
 import live_path as lp
 import multihop_witness_v14 as v14
 import session_chain_v11 as v11
except ImportError:
 from . import protected_path_v24 as v24, live_path as lp, multihop_witness_v14 as v14, session_chain_v11 as v11

NODES=v24.NODES

def output_verdict(t):return t[0] if isinstance(t,(tuple,list)) else t

def escrow_record(batch,node,index):
 """Source observation is the RECEIVER's original sealed record, not a relay report."""
 return copy.deepcopy(batch['witnesses'][node][index])

def verify_escrow_entry(entry, node, idx, tx, witness_keys):
 """Do not accept merely matching content; require source-key authentication and subject."""
 if not isinstance(entry,dict) or entry.get('node')!=v14.witness_name(node):return False
 if entry.get('body',{}).get('sequence')!=idx:return False
 if entry['body'].get('transaction_hash')!=v11.digest(tx):return False
 try:return v11.verify_seal(entry,witness_keys)
 except (AttributeError,ValueError,TypeError,KeyError):
  # v11 uses check_seal on some versions; handled below in verification by the chain verifier.
  return False

def recover(batch, store, node, idx, report_keys, witness_keys, mode='present'):
 """Recovery is fail closed; escrow is modeled as root-trusted (same domain as receiver)."""
 b=copy.deepcopy(batch)
 if node not in NODES or idx<0 or idx>=len(b.get('transactions',[])):raise ValueError('invalid location')
 baseline=output_verdict(v24.verify_batch(b,report_keys,witness_keys))
 if baseline!='UNRESOLVED':return baseline,0,'no_recovery_needed'
 key=f'{node}/{idx}'
 if mode=='absent' or key not in store:return 'UNRESOLVED',0,'trusted_receipt_unavailable'
 start=time.perf_counter_ns()
 candidate=copy.deepcopy(store[key])
 if mode=='conflicting':
  # A conflicting *signed* alternate receipt is modeled using a previously signed
  # different observation, never by generating a new signature using verifier keys.
  candidate=copy.deepcopy(store.get(f'{node}/{idx}/conflict',candidate))
 if not isinstance(candidate,dict) or candidate.get('node')!=v14.witness_name(node):
  return 'INVALID',time.perf_counter_ns()-start,'wrong_observer_identity'
 body=candidate.get('body',{})
 if body.get('sequence')!=idx or body.get('transaction_hash')!=v11.digest(b['transactions'][idx]):
  return 'INVALID',time.perf_counter_ns()-start,'wrong_transaction_or_sequence'
 # A replacement with different content and independently authentic observer MAC
 # is a conflict rather than a license to overwrite an existing trusted observation.
 original=store.get(key)
 if mode=='conflicting' and candidate!=original:
  return 'INCONSISTENT',time.perf_counter_ns()-start,'conflicting_signed_observer_receipts'
 # v2.4 verifier independently checks MAC and all hop / transaction link constraints.
 b['witnesses'][node].insert(idx,candidate)
 verdict=output_verdict(v24.verify_batch(b,report_keys,witness_keys))
 return verdict,time.perf_counter_ns()-start,'receiver_escrow_receipt_verified_by_chain_verifier'

def check_recovery(batch, report_keys, witness_keys, temp):
 node='service-a';idx=len(batch['transactions'])-1
 original=escrow_record(batch,node,idx)
 store={f'{node}/{idx}':original}
 escrow=temp/'trusted_receiver_escrow.json'
 escrow.write_text(json.dumps(store,sort_keys=True),encoding='utf-8');escrow.chmod(0o600)
 if escrow.stat().st_uid!=0 or escrow.stat().st_mode&0o077:
  raise RuntimeError('trusted escrow ownership/permissions failed')
 partial=copy.deepcopy(batch);partial['witnesses'][node].pop(idx)
 baseline=output_verdict(v24.verify_batch(partial,report_keys,witness_keys))
 if baseline!='UNRESOLVED':raise RuntimeError('missing witness did not abstain')
 reread=json.loads(escrow.read_text())
 recovered,lat,reason=recover(partial,reread,node,idx,report_keys,witness_keys)
 unrecovered,_,_=recover(partial,{},node,idx,report_keys,witness_keys,mode='absent')
 # Adversarial conflicting witness: actual signed witness from another live TLS case
 # with a different transaction; wrong transaction must be rejected without re-signing.
 other_idx=0
 if other_idx==idx:other_idx=1
 conflict_store=copy.deepcopy(reread)
 conflict_store[f'{node}/{idx}/conflict']=escrow_record(batch,node,other_idx)
 conflict,_,_=recover(partial,conflict_store,node,idx,report_keys,witness_keys,mode='conflicting')
 # Tampered MAC, transaction/hash unchanged: original signed receipt must be rejected.
 tampered=copy.deepcopy(reread);r=tampered[f'{node}/{idx}'];r['mac']='0'*len(r['mac'])
 modified,_,_=recover(partial,tampered,node,idx,report_keys,witness_keys)
 return {'baseline':baseline,'recovered':recovered,'unavailable':unrecovered,
  'conflicting':conflict,'tampered':modified,'recovery_wall_ns_single':lat,
  'escrow_root_owned':True,'escrow_mode':'0600','recovery_source':'actual live receiver receipt'}

def run(args):
 if os.geteuid()!=0:raise RuntimeError('Root needed only for isolated lab TLS receivers and protected escrow')
 if ssl.OPENSSL_VERSION_INFO[:2]<(3,5):raise RuntimeError('Python OpenSSL >= 3.5 required')
 if not 2<=args.count<=50:raise ValueError('count must be 2..50')
 if not 1<=args.trials<=20:raise ValueError('trials must be 1..20')
 ident=pwd.getpwnam(args.attacker_user)
 if ident.pw_uid==0:raise ValueError('attacker must be unprivileged')
 root=Path(args.archive).resolve();root.mkdir(parents=True,exist_ok=True)
 tag=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'_'+uuid.uuid4().hex[:8]
 path=root/('recovery_'+tag);path.mkdir()
 rows=[];manifest={'schema':'pqc-v26-recovery-campaign','created_utc':datetime.now(timezone.utc).isoformat(),
  'openssl':ssl.OPENSSL_VERSION,'model':'live three-hop v2.4 sessions; receiver receipt escrow same root trust domain',
  'trial_count':args.trials,'transactions_per_connection':args.count,'trials':[],
  'limits':['root holds all receiver escrow keys; not independent receiver trust domains',
  'fresh real TLS sessions in each trial; evidence removal/recovery occurs offline',
  'no external cryptographic channel binding; handshake labels are public',
  'single missing receiver receipt per batch; no live retransmission protocol',
  'conflict uses different original signed transaction receipt; not a same-transaction conflicting signer',
  'latency measures in-process Python recovery and verification only, not network fetch',
  'TLS self-signed certificates unvalidated; hybrid key exchange only']}
 def save(fname,data): (path/fname).write_text(json.dumps(data,indent=2,sort_keys=True)+'\n')
 save('manifest.json',manifest)
 for i in range(args.trials):
  out={'trial':i+1,'status':'FAILED'};tick=time.perf_counter_ns()
  try:
   with tempfile.TemporaryDirectory(prefix='pqc-v26-',dir='/var/tmp') as td:
    temp=Path(td);temp.chmod(0o755)
    cert,private=lp.make_cert(temp,args.openssl)
    probe=temp/'receiver_private_secret';probe.write_bytes(secrets.token_bytes(32));probe.chmod(0o600)
    report_keys={n:secrets.token_bytes(32) for n in ('client',)+NODES}
    witness_keys={v14.witness_name(n):secrets.token_bytes(32) for n in NODES}
    good=v24.run_case(cert,private,args.count,'hybrid',report_keys,witness_keys,ident.pw_uid,ident.pw_gid,probe,args.attacker_user)
    bad=v24.run_case(cert,private,args.count,'classical_middle',report_keys,witness_keys,ident.pw_uid,ident.pw_gid,probe,args.attacker_user)
    if output_verdict(v24.verify_batch(good,report_keys,witness_keys))!='SATISFIED':raise RuntimeError('live hybrid base failed')
    if output_verdict(v24.verify_batch(bad,report_keys,witness_keys))!='VIOLATED':raise RuntimeError('live classical base failed')
    good_check=check_recovery(good,report_keys,witness_keys,temp)
    bad_check=check_recovery(bad,report_keys,witness_keys,temp)
    expected={'baseline':'UNRESOLVED','recovered':'SATISFIED','unavailable':'UNRESOLVED','conflicting':'INVALID','tampered':'INVALID'}
    for key,val in expected.items():
     if good_check[key]!=val:raise RuntimeError('hybrid '+key+': '+good_check[key])
    if bad_check['recovered']!='VIOLATED':raise RuntimeError('classical recovered: '+bad_check['recovered'])
    if not (good['attacker_key_denied'] and bad['attacker_key_denied']):raise RuntimeError('key read denied not shown')
    out.update(status='PASS',hybrid=good_check,classical_middle=bad_check,attacker_key_read_denied=True,
       negotiated_hybrid=['X25519MLKEM768']*3,negotiated_classical_middle=['X25519MLKEM768','X25519','X25519MLKEM768'])
  except Exception as exc:out['error']=repr(exc)
  out['elapsed_wall_ns']=time.perf_counter_ns()-tick
  manifest['trials'].append({'trial':i+1,'status':out['status']})
  save('trial_%03d.json'%(i+1),out);save('manifest.json',manifest)
  rows.append({'trial':i+1,'status':out['status'],'baseline':out.get('hybrid',{}).get('baseline',''),
    'recovered':out.get('hybrid',{}).get('recovered',''),'unavailable':out.get('hybrid',{}).get('unavailable',''),
    'conflict':out.get('hybrid',{}).get('conflicting',''),'tampered':out.get('hybrid',{}).get('tampered',''),
    'classical_recovered':out.get('classical_middle',{}).get('recovered',''),
    'single_recovery_wall_ns':out.get('hybrid',{}).get('recovery_wall_ns_single',''),
    'trial_wall_ns':out['elapsed_wall_ns']})
  print(f"trial_{i+1:03d}: {out['status']} recovered={rows[-1]['recovered']} classical={rows[-1]['classical_recovered']}",flush=True)
 with (path/'summary.csv').open('w',newline='') as f:
  w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
 manifest['successes']=sum(x['status']=='PASS' for x in rows);manifest['failures']=len(rows)-manifest['successes']
 save('manifest.json',manifest)
 import hashlib
 with (path/'checksums.sha256').open('w') as f:
  for p in sorted(path.glob('*')):
   if p.name!='checksums.sha256' and p.is_file():f.write(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.name+'\n')
 print('ARCHIVE:',path,flush=True)
 if manifest['failures']:raise SystemExit(2)
 print('PASS: live receiver witness recovery; unresolved absence preserved; evidence archived',flush=True)

def main():
 p=argparse.ArgumentParser();p.add_argument('--openssl',default='openssl');p.add_argument('--archive',default='results/evidence_recovery_v26')
 p.add_argument('--trials',type=int,default=3);p.add_argument('--count',type=int,default=3);p.add_argument('--attacker-user',default='nobody')
 a=p.parse_args();run(a)
if __name__=='__main__':main()
